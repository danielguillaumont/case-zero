def test_record_limit_and_unicode_xml_boundaries(tmp_path):
    original = SOURCE.read_bytes().splitlines()[0]
    field = b'<Data Name="CommandLine" />'
    line = original.replace(field, b'<Data Name="CommandLine">&#x1F642;</Data>')
    capped = line.ljust(MAX_RECORD_BYTES)
    path = tmp_path / "capture.xml"
    path.write_bytes(
        b"\n".join(
            (
                capped,
                capped + b" ",
                original.replace(field, b'<Data Name="CommandLine">&#xD800;</Data>'),
                original[:-1],
            )
        )
        + b"\n"
    )
    result = load_sysmon_telemetry(path)
    assert [event.fields["command_line"] for event in result.events] == ["\U0001f642"]
    assert [(item.ordinal, item.code) for item in result.diagnostics] == [
        (1, "record_too_large"),
        (2, "malformed_xml"),
        (3, "malformed_xml"),
    ]
